import { expect, test } from '@playwright/test'

test('owner-operated messaging, scheduling and benefit visuals stay accurate', async ({ page }, info) => {
  await page.route('**/api/inquiries/csrf/', route => route.fulfill({ json: { csrfToken: 'test-csrf' } }))
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Keep the things.Reclaim the space.')
  await expect(page.locator('#care')).toContainText('Local storage. A direct line.')
  await expect(page.locator('#care')).toContainText('sole-proprietor')
  await expect(page.locator('#care')).not.toContainText('Only Blake')
  await expect(page.locator('main')).not.toContainText('48 hours')
  await expect(page.locator('main')).not.toContainText('business closes')
  await expect(page.locator('.route-note')).toContainText('at least 72 hours ahead')
  await expect(page.locator('.hero-benefit-visual .plan-visual')).toHaveCount(1)
  await expect(page.locator('.hero-benefit-visual')).toContainText('Image coming soon.')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('owner-operated-home.png') })
  await expect(page.locator('.hero-actions').getByRole('link', { name: 'Get my storage plan' })).toHaveAttribute('href', 'http://127.0.0.1:8000/enroll/')
  await page.goto('/plans')
  await expect(page.locator('#partial-return').locator('..')).toContainText('at least 72 hours ahead')
  await expect(page.locator('[data-asset-key="attic-storage-hassle"]')).toContainText('outside your home')
  await page.goto('/policies/storage-agreement')
  await expect(page.locator('#appointments')).toContainText('at least 72 hours ahead')
  await expect(page.locator('#interruptions')).toContainText('close the business, we coordinate return without a cancellation or final-return fee')
  await expect(page.locator('#interruptions')).toContainText('Authorized backup personnel may assist')
  await expect(page.locator('.policy-version')).toContainText('2026-10-19.3')
})
