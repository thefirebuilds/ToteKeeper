test('form is keyboard navigable, has no horizontal overflow and exposes accessible field errors', async ({ page }, info) => {
  await page.route('**/api/inquiries/', route => route.fulfill({ status: 400, json: { error: 'Please check the highlighted fields.', fields: { email: ['Please check your email address.'] } } }))
  await page.goto('/')
  await page.getByRole('button', { name: 'Help me decide', exact: true }).click()
  await expect(page.getByLabel('Your name', { exact: true })).toBeFocused()
  await page.keyboard.type('A Fictional Customer')
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Email address', { exact: true })).toBeFocused()
  await page.keyboard.type('customer@example.com')
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('ZIP code', { exact: true })).toBeFocused()
  await page.keyboard.type('78610')
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Plan interest')).toBeFocused()
  await page.keyboard.press('Tab')
  await page.keyboard.type('Holiday decorations')
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Phone optional')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Preferred reply method')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('form').getByRole('button', { name: 'Get my storage plan' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Email address', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByRole('alert')).toBeVisible()
  const overflows = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflows).toBe(false)
  await page.locator('#interest').screenshot({ path: info.outputPath('inquiry.png') })
})
